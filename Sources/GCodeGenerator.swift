import Foundation

enum CornerType: String, CaseIterable, Identifiable {
    case radius = "R 圆角"
    case chamfer = "C 倒角"
    case square = "直角"

    var id: String { rawValue }
}

struct PocketSpec {
    var length: Double = 120
    var width: Double = 80
    var depth: Double = 10
    var cornerType: CornerType = .radius
    var cornerValue: Double = 8
    var toolDia: Double = 12
    var stepDown: Double = 3
    var stepOver: Double = 6
    var spindle: Int = 2000
    var feed: Int = 400
    var safeZ: Double = 100
    var compNo: Int = 1
    var compact: Bool = true

    var toolRadius: Double { toolDia / 2 }

    /// 空数组表示可以生成
    var issues: [String] {
        var out: [String] = []
        if length <= 0 || width <= 0 || depth <= 0 { out.append("长宽深必须大于 0") }
        if toolDia <= 0 { out.append("刀具直径必须大于 0") }
        if toolDia >= min(length, width) { out.append("刀具直径必须小于型腔最小边") }
        if stepDown <= 0 { out.append("每层切深必须大于 0") }
        if cornerType != .square && cornerValue <= 0 { out.append("R/C 值必须大于 0，或选「直角」") }
        if cornerType == .radius && cornerValue < toolRadius {
            out.append("圆角 R 小于刀具半径，壁面无法一刀到位，需换小刀或先清角")
        }
        if cornerType == .chamfer && cornerValue > min(length, width) / 2 { out.append("倒角 C 过大") }
        if stepOver <= 0 || stepOver > toolDia { out.append("行距应在 0 到刀具直径之间") }
        return out
    }

    var canGenerate: Bool { issues.isEmpty }
}

enum GCodeGenerator {

    static func fmt(_ v: Double, _ digits: Int = 3) -> String {
        let f = NumberFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.numberStyle = .decimal
        f.usesGroupingSeparator = false
        f.minimumFractionDigits = digits
        f.maximumFractionDigits = digits
        return f.string(from: NSNumber(value: v)) ?? String(v)
    }

    static func generate(_ s: PocketSpec) -> String {
        var L: [String] = []

        L.append("%")
        L.append("O1001 (SQUARE POCKET MACRO)")
        L.append("( L=\(fmt(s.length)) W=\(fmt(s.width)) D=\(fmt(s.depth)) )")
        L.append("( CORNER=\(cornerDesc(s)) TOOL=\(fmt(s.toolDia)) )")
        L.append("( AP=\(fmt(s.stepDown)) AE=\(fmt(s.stepOver)) S\(s.spindle) F\(s.feed) )")
        L.append("( GENERATED BY MACROGEN - CHECK BEFORE RUN )")
        L.append("")
        L.append("G21 G40 G49 G80 G90 G54")
        L.append("G00 Z\(fmt(s.safeZ))")
        L.append("M03 S\(s.spindle)")
        L.append("")
        L.append("#1=\(fmt(s.length)) (L)")
        L.append("#2=\(fmt(s.width)) (W)")
        L.append("#3=\(fmt(s.depth)) (D)")
        L.append("#4=\(fmt(s.cornerValue)) (R OR C)")
        L.append("#5=\(fmt(s.toolDia)) (TOOL DIA)")
        L.append("#6=\(fmt(s.stepDown)) (AP)")
        L.append("#7=\(fmt(s.stepOver)) (AE)")
        L.append("#8=\(s.spindle) (S)")
        L.append("#9=\(s.feed) (F)")
        L.append("#10=\(fmt(s.safeZ)) (SAFE Z)")
        L.append("#20=[#1/2.] (A)")
        L.append("#21=[#2/2.] (B)")
        L.append("#22=[#5/2.] (TOOL R)")
        L.append("#23=0. (CUR DEPTH)")
        L.append("")
        L.append("( === ROUGHING LAYERS === )")
        L.append("WHILE[#23LT#3]DO1")
        L.append("#23=#23+#6")
        L.append("IF[#23GT#3]THEN#23=#3")
        L.append("#26=-#23")
        L.append("( RAMP IN )")
        L.append("G00 X0 Y0")
        L.append("G01 Z[#26+1.5] F[#9]")
        L.append("G01 X[#20/3.] Z#26 F[#9/2.]")
        L.append("#24=0 (RING)")
        L.append("WHILE[[#22+#24*#7]LE[#21-0.5]]DO2")
        L.append("#30=[#22+#24*#7] (INSET)")
        L.append("#27=[#20-#30] (RING A)")
        L.append("#28=[#21-#30] (RING B)")
        L.append("#29=[#4-#30] (RING CORNER)")
        L.append("IF[#29LT0.]THEN#29=0.")
        if s.cornerType == .radius {
            L.append("IF[#29LT0.001]THEN#29=0.001")
        }
        L.append("#24=#24+1")
        if s.compact {
            L.append(contentsOf: ringBlocksCompact(s))
        } else {
            L.append(contentsOf: ringBlocks(type: s.cornerType, approach: "G01 X#27 Y0 F[#9]"))
        }
        L.append("END2")
        L.append("END1")
        L.append("")
        L.append("( === FINISH WALL PASS G41 === )")
        L.append("#27=#20")
        L.append("#28=#21")
        L.append("#29=#4")
        L.append("G00 Z[#26+2.]")
        L.append("G00 X[#27+6.] Y0")
        L.append("G01 Z#26 F[#9]")
        L.append("G41 D\(s.compNo) G01 X#27 Y0 F[#9]")
        if s.compact {
            L.append(contentsOf: ringBlocksCompact(s))
        } else {
            L.append(contentsOf: ringBlocks(type: s.cornerType))
        }
        L.append("G40 G01 X[#27+6.] Y0")
        L.append("G00 Z#10")
        L.append("M05")
        L.append("M30")
        L.append("%")

        guard s.compact else { return L.joined(separator: "\n") }
        var lean: [String] = []
        for line in L {
            var t = line
            if let r = t.range(of: "\\([^)]*\\)", options: .regularExpression) {
                t.removeSubrange(r)
            }
            t = t.trimmingCharacters(in: .whitespaces)
            if !t.isEmpty { lean.append(t) }
        }
        return lean.joined(separator: "\n")
    }

    private static func cornerDesc(_ s: PocketSpec) -> String {
        switch s.cornerType {
        case .radius: return "R\(fmt(s.cornerValue, 2))"
        case .chamfer: return "C\(fmt(s.cornerValue, 2))"
        case .square: return "NONE"
        }
    }

    /// 精简写法：用 FANUC 自动倒圆/倒角 ,R / ,C
    private static func ringBlocksCompact(_ s: PocketSpec) -> [String] {
        var sfx = ""
        if s.cornerType == .radius { sfx = ",R[#29]" }
        else if s.cornerType == .chamfer { sfx = ",C[#29]" }
        var out: [String] = []
        out.append("G01X#27Y0F[#9]")
        out.append("G01X#27Y#28" + sfx)
        out.append("G01X[-#27]Y#28" + sfx)
        out.append("G01X[-#27]Y[-#28]" + sfx)
        out.append("G01X#27Y[-#28]" + sfx)
        out.append("G01X#27Y0" + sfx)
        return out
    }

    /// 逆时针轮廓，从 (A,0) 出发；与 G41 左补偿配合=内腔顺铣
    private static func ringBlocks(type: CornerType, approach: String? = nil) -> [String] {
        var out: [String] = []
        if let a = approach { out.append(a) }
        switch type {
        case .radius:
            out.append("G01 Y[#28-#29]")
            out.append("G03 X[#27-#29] Y#28 R#29")
            out.append("G01 X[#29-#27]")
            out.append("G03 X[-#27] Y[#28-#29] R#29")
            out.append("G01 Y[#29-#28]")
            out.append("G03 X[#29-#27] Y[-#28] R#29")
            out.append("G01 X[#27-#29]")
            out.append("G03 X#27 Y[#29-#28] R#29")
            out.append("G01 Y0")
        case .chamfer:
            out.append("G01 Y[#28-#29]")
            out.append("G01 X[#27-#29] Y#28")
            out.append("G01 X[#29-#27]")
            out.append("G01 X[-#27] Y[#28-#29]")
            out.append("G01 Y[#29-#28]")
            out.append("G01 X[#29-#27] Y[-#28]")
            out.append("G01 X[#27-#29]")
            out.append("G01 X#27 Y[#29-#28]")
            out.append("G01 Y0")
        case .square:
            out.append("G01 Y#28")
            out.append("G01 X[-#27]")
            out.append("G01 Y[-#28]")
            out.append("G01 X#27")
            out.append("G01 Y0")
        }
        return out
    }
}
