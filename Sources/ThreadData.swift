    static func metricRows(coarse: Bool) -> [ThreadRow] {
        let data = coarse ? mCoarse : mFine
        return data.map { d, p in
            let name = coarse ? "M" + trim(d) : "M" + trim(d) + "×" + trim(p)
            return ThreadRow(name: name, pitchText: trim(p),
                             drill: String(format: "%.2f", d - p),
                             squeeze: String(format: "%.2f", d - p / 2))
        }
    }

    static func inchRows(_ data: [(String, String, String, String)]) -> [ThreadRow] {
        data.map { ThreadRow(name: $0.0, pitchText: $0.1 + "牙/" + $0.2,
                             drill: $0.3, squeeze: "—") }
    }

    static func trim(_ v: Double) -> String {
        v == v.rounded() ? String(Int(v)) : String(v)
    }
